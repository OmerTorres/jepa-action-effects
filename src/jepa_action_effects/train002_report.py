"""TRAIN-002 generated tables (D035). Values come only from the sealed summary."""

from __future__ import annotations

from typing import Any

from jepa_action_effects.train001_protocol import MAGNITUDES, READOUTS, SCENES, magnitude_label
from jepa_action_effects.train002_metrics import ARMS


def _fmt(entry: dict[str, Any] | None, digits: int = 2) -> str:
    if not entry or entry.get("estimate") is None:
        return "—"
    text = f"{entry['estimate']:.{digits}f}"
    if entry.get("ci"):
        low, high = entry["ci"]
        text += f" [{low:.{digits}f}, {high:.{digits}f}]"
    return text


def _num(value: float | None, digits: int = 2) -> str:
    return "—" if value is None else f"{value:.{digits}f}"


def draft(manifest: dict[str, Any]) -> str:
    summary = manifest["summary"]
    primary = summary["readouts"][READOUTS[0]]
    boot = primary["bootstrap"]
    lines = [
        "# TRAIN-002 generated tables (D035)",
        "",
        "Generated by `python -m jepa_action_effects.train002 report`; do not edit.",
        f"Primary readout `{READOUTS[0]}`. Errors are absolute terminal block-position errors "
        "(world units), seed-averaged per arm; intervals are 2,000 scene-stratified paired "
        "family bootstrap draws.",
        "",
        f"- Measurement gate at 0.60 (confirmation real frames): {summary['gate_passed_0.60']}",
        f"- Primary verdict: **{summary['primary_verdict']}**",
        f"- Generic fine-tuning verdict: **{summary['generic_verdict']}**",
        f"- Readout sign agreement: {summary['readout_agreement']}",
        "",
        "## Mean error by arm",
        "",
        "| Arm | 0.45 (in support) | 0.60 (held out for dose_omitted) |",
        "| --- | ---: | ---: |",
    ]
    for arm in ARMS:
        lines.append(
            f"| {arm} | {_num(primary['means_0.45'].get(arm))} | "
            f"{_num(primary['means_0.60'].get(arm))} |"
        )
    lines += [
        "",
        "## Contrasts",
        "",
        "| Contrast | 0.60 estimate [95% CI] | challenge | archive |",
        "| --- | --- | --- | --- |",
    ]
    for name, entry in boot.items():
        scenes = entry.get("by_scene", {})
        lines.append(
            f"| {name} | {_fmt(entry)} | {_fmt(scenes.get('challenge'))} | "
            f"{_fmt(scenes.get('archive'))} |"
        )
    tf = primary["transfer_fraction"]
    lines += [
        "",
        f"Transfer fraction at 0.60: {_fmt(tf)} ({tf['note']}).",
        "",
        "Per-seed dose_omitted − balanced at 0.60: "
        + ", ".join(
            f"{k} {v:.2f}" for k, v in primary["per_seed_dose_omitted_minus_balanced"].items()
        ),
        "",
        "## Pred/real projection-slope ratio R",
        "",
        "| Arm | "
        + " | ".join(f"{s} {magnitude_label(m)}" for s in SCENES for m in MAGNITUDES)
        + " |",
        "| --- | " + " | ".join("---:" for _ in SCENES for _ in MAGNITUDES) + " |",
    ]
    for arm in ARMS:
        cells = primary["slope_ratios"].get(arm, {})
        values = [
            _num(cells.get(f"{s}:{magnitude_label(m)}", {}).get("ratio"))
            for s in SCENES
            for m in MAGNITUDES
        ]
        lines.append(f"| {arm} | " + " | ".join(values) + " |")
    latent = summary["latent_0.60"]
    lines += [
        "",
        "## Terminal latent MSE at 0.60",
        "",
        "Means: " + ", ".join(f"{k} {v:.4f}" for k, v in latent["means"].items()),
        "",
        *(f"- {k}: {_fmt(v, 4)}" for k, v in latent["bootstrap"].items()),
        "",
        "## Ordinary archive windows (error relative to frozen)",
        "",
        "Means: " + ", ".join(f"{k} {v:.2f}" for k, v in primary["ordinary"]["means"].items()),
        "",
        *(f"- {k}: {_fmt(v)}" for k, v in primary["ordinary"]["bootstrap"].items()),
        "",
        "## Readout sensitivity (0.60 contrasts)",
        "",
        "| Readout | dose_omitted − balanced | frozen − archive_only | primary verdict |",
        "| --- | --- | --- | --- |",
    ]
    for readout, block in summary["readouts"].items():
        b = block["bootstrap"]
        lines.append(
            f"| {readout} | {_fmt(b['dose_omitted_minus_balanced'])} | "
            f"{_fmt(b['frozen_minus_archive_only'])} | {block['primary_verdict']} |"
        )
    gate = manifest["gate"]
    lines += [
        "",
        "## Measurement gates (confirmation real frames, primary readout)",
        "",
        "| Cell | moved | slope_real CI | floor | passed |",
        "| --- | ---: | --- | ---: | --- |",
    ]
    for cell, value in gate["cells"].items():
        ci = value["slope_real_ci"]
        ci_text = "—" if ci is None else f"[{ci[0]:.3f}, {ci[1]:.3f}]"
        lines.append(
            f"| {cell} | {value['moved']} | {ci_text} | {_num(value['floor'], 3)} | "
            f"{value['passed']} |"
        )
    lines += [
        "",
        "## Training runs",
        "",
        "| Run | units | first-100 loss | last-100 loss | s |",
        "| --- | ---: | ---: | ---: | ---: |",
    ]
    for run_id, run in manifest["runs"].items():
        g = run["optimization_gate"]
        lines.append(
            f"| {run_id} | {run['training_units']} | {g['first_mean']:.5f} | "
            f"{g['last_mean']:.5f} | {run['seconds']:.0f} |"
        )
    return "\n".join(lines) + "\n"
