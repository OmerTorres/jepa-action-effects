"""SUPPORT-001 generated tables (D036). Values come only from sealed outputs."""

from __future__ import annotations

from typing import Any

from jepa_action_effects.support001_metrics import ACCOUNTS
from jepa_action_effects.train001_protocol import READOUTS, SCENES, magnitude_label

DOSES = (0.15, 0.30, 0.45, 0.60, 0.80, 1.00)


def _fmt(entry: dict[str, Any] | None, digits: int = 2, key: str = "ci") -> str:
    if not entry or entry.get("estimate") is None:
        return "—"
    text = f"{entry['estimate']:.{digits}f}"
    interval = entry.get(key)
    if interval:
        text += f" [{interval[0]:.{digits}f}, {interval[1]:.{digits}f}]"
    return text


def draft(manifest: dict[str, Any]) -> str:
    summary, fit = manifest["summary"], manifest["fit"]
    primary = summary["readouts"][READOUTS[0]]
    lines = [
        "# SUPPORT-001 generated tables (D036)",
        "",
        "Generated by `python -m jepa_action_effects.support001 report`; do not edit.",
        "",
        f"- Support map: {manifest['map']['windows']} archive windows; command magnitude "
        + ", ".join(
            f"{k} {v:.3f}" for k, v in manifest["map"]["command_magnitude_quantiles"].items()
        ),
        f"- Fresh families: {summary['families']}; gated over-range branches: "
        f"{summary['gated_branches']}",
        f"- **Verdict (primary readout): {summary['verdict']}**; "
        f"readout agreement {summary['readout_agreement']}",
        "",
        "## Account fits (development: opened TRAIN-001 frozen records)",
        "",
        "| Account | parameters | development MSE |",
        "| --- | --- | ---: |",
    ]
    for name in ACCOUNTS:
        f = fit["fits"][name]
        params = ", ".join(f"{v:.3f}" for v in f["params"])
        lines.append(f"| {name} | {params} | {f['mean_squared_error']:.1f} |")
    lines += [
        "",
        "## Fresh-family squared error by account (primary readout)",
        "",
        "| Account | over-range (0.80, 1.00) | in-range (0.15–0.60) |",
        "| --- | ---: | ---: |",
    ]
    for name in ACCOUNTS:
        lines.append(
            f"| {name} | {primary['mean_over_range'][name]:.1f} | "
            f"{primary['mean_in_range'][name]:.1f} |"
        )
    boot = primary.get("over_range_bootstrap", {})
    lines += ["", "Over-range paired contrasts (X − Y; negative favours X):", ""]
    for key, value in boot.items():
        lines.append(f"- {key}: {_fmt(value, 1)}")
    lines += [
        "",
        "## Dose response (primary readout, block, all branches)",
        "",
        "| Scene | Dose | b_rev | pred/real (moved) | energy ratio | alignment |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    cells = primary["dose_response"][f"{READOUTS[0]}:block"]
    for scene in SCENES:
        for dose in DOSES:
            c = cells.get(scene, {}).get(magnitude_label(dose))
            if not c:
                continue
            lines.append(
                f"| {scene} | {dose:.2f} | {_fmt(c['b_rev'], 3, 'ci95')} | "
                f"{_fmt(c['ratio_moved'], 3, 'ci95')} | {_fmt(c['energy_ratio'], 3, 'ci95')} | "
                f"{_fmt(c['alignment'], 3, 'ci95')} |"
            )
    lines += [
        "",
        "## Agent probe (decoded agent displacement, primary readout)",
        "",
        "| Scene | Dose | b_rev | pred/real (moved) | energy ratio |",
        "| --- | --- | --- | --- | --- |",
    ]
    cells = primary["agent_probe"][f"{READOUTS[0]}:agent"]
    for scene in SCENES:
        for dose in DOSES:
            c = cells.get(scene, {}).get(magnitude_label(dose))
            if not c:
                continue
            lines.append(
                f"| {scene} | {dose:.2f} | {_fmt(c['b_rev'], 3, 'ci95')} | "
                f"{_fmt(c['ratio_moved'], 3, 'ci95')} | {_fmt(c['energy_ratio'], 3, 'ci95')} |"
            )
    lines += [
        "",
        "## Support covariates on fresh families (median)",
        "",
        "| Cell | log support ℓ | command quantile within neighbourhood |",
        "| --- | ---: | ---: |",
    ]
    for cell, value in primary["covariates"].items():
        lines.append(
            f"| {cell} | {value['log_support_median']:.2f} | "
            f"{value['magnitude_quantile_median']:.2f} |"
        )
    lines += [
        "",
        "## Measurement gates (real frames, primary readout)",
        "",
        "| Cell | moved | slope_real CI | floor | passed |",
        "| --- | ---: | --- | ---: | --- |",
    ]
    for cell, value in manifest["gate"].items():
        ci = value["slope_real_ci"]
        ci_text = "—" if ci is None else f"[{ci[0]:.3f}, {ci[1]:.3f}]"
        floor = "—" if value["floor"] is None else f"{value['floor']:.3f}"
        lines.append(f"| {cell} | {value['moved']} | {ci_text} | {floor} | {value['passed']} |")
    lines += ["", "## Readout sensitivity", ""]
    for readout, block in summary["readouts"].items():
        lines.append(f"- {readout}: {block['decision']['verdict']}")
    return "\n".join(lines) + "\n"
